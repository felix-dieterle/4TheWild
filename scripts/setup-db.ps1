#requires -Version 5.1
<#
.SYNOPSIS
    Creates the 4thewild MariaDB database, the application user and the schema.

.DESCRIPTION
    Uses the local XAMPP MariaDB (root, no password) to create the database and
    a dedicated user. Credentials are written to config.local.php inside the
    deploy directory - the file is git-ignored and never printed.

.NOTES
    ASCII only (PowerShell 5.1 without BOM).
#>
param(
    [string]$DeployDir = 'F:\CascadeProjects\mama-razzi\public\apps\wild',
    [string]$SchemaFile = 'F:\oc-projects\4TheWild\apps\wild\db\schema.sql'
)

$ErrorActionPreference = 'Stop'

$mysql  = 'F:\prg\xampp\mysql\bin\mysql.exe'
$dbName = '4thewild'
$dbUser = 'wild4'

if (-not (Test-Path -LiteralPath $mysql)) { throw "mysql.exe not found: $mysql" }
if (-not (Test-Path -LiteralPath $SchemaFile)) { throw "schema not found: $SchemaFile" }

New-Item -ItemType Directory -Path $DeployDir -Force | Out-Null
$configFile = Join-Path $DeployDir 'config.local.php'

& $mysql -u root -e 'CREATE DATABASE IF NOT EXISTS `4thewild` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;'
if ($LASTEXITCODE -ne 0) { throw 'CREATE DATABASE failed' }

if (-not (Test-Path -LiteralPath $configFile)) {
    $bytes = New-Object byte[] 24
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)
    $password = [Convert]::ToBase64String($bytes).Replace('+', 'x').Replace('/', 'y').Replace('=', '')

    $sqlFile = Join-Path $env:TEMP ('wild-db-setup-' + [Guid]::NewGuid().ToString('N') + '.sql')
    $sql = @"
CREATE USER IF NOT EXISTS '$dbUser'@'localhost' IDENTIFIED BY '$password';
ALTER USER '$dbUser'@'localhost' IDENTIFIED BY '$password';
GRANT SELECT, INSERT, UPDATE, DELETE ON ``4thewild``.* TO '$dbUser'@'localhost';
FLUSH PRIVILEGES;
"@
    [IO.File]::WriteAllText($sqlFile, $sql, (New-Object Text.UTF8Encoding($false)))
    try {
        cmd /c "`"$mysql`" -u root < `"$sqlFile`""
        if ($LASTEXITCODE -ne 0) { throw 'CREATE USER / GRANT failed' }
    } finally {
        Remove-Item -LiteralPath $sqlFile -Force -ErrorAction SilentlyContinue
    }

    $php = @"
<?php
// Generated by scripts/setup-db.ps1 - git-ignored, contains DB credentials.
declare(strict_types=1);

return [
    'host'    => 'localhost',
    'port'    => '3306',
    'name'    => '$dbName',
    'user'    => '$dbUser',
    'pass'    => '$password',
    'charset' => 'utf8mb4',
];
"@
    [IO.File]::WriteAllText($configFile, $php, (New-Object Text.UTF8Encoding($false)))
    Write-Output "config.local.php created for user $dbUser"
} else {
    Write-Output 'config.local.php already exists - credentials left untouched'
}

cmd /c "type `"$($SchemaFile.Replace('/','\'))`" | `"$mysql`" -u root 4thewild"
if ($LASTEXITCODE -ne 0) { throw 'schema.sql import failed' }

$tables = & $mysql -u root -N -e "SHOW TABLES FROM 4thewild;"
Write-Output ('tables: ' + ($tables -join ', '))
